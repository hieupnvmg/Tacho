keys = set()
for f in glob.glob(SRC + "/*.swift"):
    if f.endswith("Translations.swift"): continue
    s = open(f, encoding="utf-8").read()
    for m in re.finditer(r'(?<![A-Za-z0-9_])L\("((?:[^"\\]|\\.)*)"', s):
        keys.add(m.group(1))
keys |= {"Tổng quan","CPU","Bộ nhớ","Ổ đĩa","Pin","Mạng","Tiến trình","Wi-Fi","Ethernet","Di động","Loopback","Khác"}

missing = sorted(k for k in keys if k not in T)
unused = sorted(k for k in T if k not in keys)
spec = re.compile(r'%(?:\.\d+)?[dfs@%]')
bad = [(k, i) for k, v in T.items() for i, t in enumerate(v) if sorted(spec.findall(k)) != sorted(spec.findall(t))]
print("keys:", len(keys), "missing:", missing, "unused:", unused, "format mismatch:", bad)
if missing or bad: sys.exit(1)

